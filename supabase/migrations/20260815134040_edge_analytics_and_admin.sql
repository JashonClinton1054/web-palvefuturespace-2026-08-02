create table if not exists public.edge_events (
  id bigint generated by default as identity primary key,
  request_id uuid not null unique,
  visitor_id uuid not null,
  session_id uuid not null,
  event_name varchar(48) not null check (event_name ~ '^[a-z][a-z0-9_]{1,47}$'),
  path varchar(256) not null check (path like '/%' and length(path) <= 256),
  referrer_host varchar(253),
  metadata jsonb not null default '{}'::jsonb check (jsonb_typeof(metadata) = 'object' and pg_column_size(metadata) <= 2048),
  ip_hash varchar(64) check (ip_hash is null or ip_hash ~ '^[0-9a-f]{64}$'),
  country_code varchar(2) check (country_code is null or country_code ~ '^[A-Z]{2}$'),
  region varchar(96),
  city varchar(96),
  timezone varchar(64),
  latitude_coarse numeric(4,1) check (latitude_coarse between -90 and 90),
  longitude_coarse numeric(4,1) check (longitude_coarse between -180 and 180),
  asn integer check (asn is null or asn > 0),
  colo varchar(3) check (colo is null or colo ~ '^[A-Z0-9]{3}$'),
  device_type varchar(16) not null default 'unknown' check (device_type in ('desktop','mobile','tablet','bot','unknown')),
  browser varchar(24) not null default 'unknown',
  os varchar(24) not null default 'unknown',
  suspected_bot boolean not null default false,
  occurred_at timestamptz not null,
  received_at timestamptz not null default now(),
  check (occurred_at between received_at - interval '24 hours' and received_at + interval '5 minutes')
);

