create or replace function private.audit_guestbook_moderation()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if old.status is distinct from new.status then
    insert into public.admin_audit_logs(admin_user_id, action, target_type, target_id, metadata)
    values (
      auth.uid(), 'GUESTBOOK_MODERATED', 'guestbook_message', new.id::text,
      jsonb_build_object('from', old.status, 'to', new.status)
    );
  end if;
  return new;
end;
$$;
revoke execute on function private.audit_guestbook_moderation() from public, anon, authenticated;

drop trigger if exists audit_guestbook_moderation on public.guestbook_messages;
create trigger audit_guestbook_moderation
after update of status on public.guestbook_messages
for each row execute function private.audit_guestbook_moderation();

